// Package prompt snapshots interactive terminal prompts.
//
// An interactive prompt is the one thing a CLI suite normally cannot test:
// reaching one means blocking on a terminal that is not there. radish already
// solves the hard half by keeping prompts as pure Models behind a swappable
// I/O edge - this package supplies the other half, turning a scripted keystroke
// sequence into a snapshot section and the frames it renders into a channel.
//
//	### KEYS ###
//	down
//	enter
//	### FRAMES ###
//	--- frame 0 (initial) ---
//	Pick an option
//	> Hamburger
//	  Pizza
//	--- frame 1 (down) ---
//	Pick an option
//	  Hamburger
//	> Pizza
//	--- frame 2 (enter) ---
//	Pick an option Pizza
//
// KEYS is hand-authored; FRAMES is regenerated by -update like any other
// output channel.
package prompt

import (
	"fmt"
	"strings"

	snap "github.com/amterp/go-snap"
	"github.com/amterp/radish"
)

// KeysSection and FramesSection are the section declarations to add to a
// Suite. They are ordinary Input and Output values - this package adds a
// vocabulary, not a mechanism.
var (
	KeysSection = snap.Input{Name: "KEYS", List: true}

	FramesSection = snap.Output{Name: "FRAMES"}
)

// ParseKeys converts KEYS tokens into radish events.
//
// A token is either a named key - "down", "enter", "ctrl-c", "space", and the
// rest of radish's vocabulary - or a "quoted string" typed one rune at a time.
// The names come from radish itself rather than a table here, so the two can
// never drift apart.
func ParseKeys(tokens []string) ([]radish.Event, error) {
	var events []radish.Event
	for _, raw := range tokens {
		token := strings.TrimSpace(raw)
		if token == "" {
			continue
		}
		if len(token) >= 2 && strings.HasPrefix(token, `"`) && strings.HasSuffix(token, `"`) {
			for _, r := range token[1 : len(token)-1] {
				events = append(events, radish.RuneEvent(r))
			}
			continue
		}
		ev, ok := radish.ParseKeyName(token)
		if !ok {
			return nil, fmt.Errorf("unknown key token %q: write a named key (down, enter, ctrl-c, space, ...) "+
				"or a %q literal to type characters", token, "quoted")
		}
		events = append(events, ev)
	}
	return events, nil
}

// Driver builds a ScriptDriver that will replay the given KEYS tokens.
func Driver(tokens []string) (*radish.ScriptDriver, error) {
	events, err := ParseKeys(tokens)
	if err != nil {
		return nil, err
	}
	return radish.NewScriptDriver(events), nil
}

// RenderFrames formats everything a driver recorded as the FRAMES channel
// value: every frame, labeled with the keystroke that produced it.
//
// Labeling matters more than it looks. A wall of undifferentiated frames says
// what the prompt drew; a labeled one says what it drew *in response to what*,
// which is the only form in which a reviewer can tell a rendering bug from an
// input-handling bug.
func RenderFrames(d *radish.ScriptDriver) string {
	frames := d.Frames()
	events := d.Events()
	eventIdx := d.FrameEventIdx()

	var b strings.Builder
	for i, frame := range frames {
		label := "initial"
		if idx := eventIdx[i]; idx >= 0 && idx < len(events) {
			label = events[idx].String()
		}
		fmt.Fprintf(&b, "--- frame %d (%s) ---\n", i, label)
		b.WriteString(frame)
		if !strings.HasSuffix(frame, "\n") {
			b.WriteString("\n")
		}
	}
	return strings.TrimSuffix(b.String(), "\n")
}

// NoKeys is the driver to install when a case scripts no keystrokes.
//
// Reaching a prompt without keys is a test-authoring mistake, and the harmful
// failure mode is not the mistake but its symptom: a driver that falls through
// to the real terminal blocks forever, and a hung suite reads as an infra
// problem rather than a missing KEYS section. Failing immediately, with the fix
// named, is worth the small type.
type NoKeys struct{}

// Run reports the missing script rather than touching a terminal.
func (NoKeys) Run(m radish.Model) (radish.Result, radish.Model, error) {
	return radish.Result{}, m, fmt.Errorf(
		"interactive prompt reached without scripted keys: add a %s section to this case", KeysSection.Name)
}
